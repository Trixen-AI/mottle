// Builds the Mottle logo from one source: the dappled 3x3 mark + the MOTTLE wordmark
// outlined from Tektur 600. Writes the React path data, the SVG files and the PNG exports.
// Run: node scripts/build-logo.mjs
import fs from 'node:fs'
import path from 'node:path'
import opentype from 'opentype.js'
import { Resvg } from '@resvg/resvg-js'

const root = path.resolve(import.meta.dirname, '..')
const fontFile = path.join(root, 'node_modules/@fontsource/tektur/files/tektur-latin-600-normal.woff')

// Palette (mirrors src/styles/tokens.css)
const INK = '#0a0b0a'
const PAPER = '#f1f0eb'
const LICHEN = '#c9f26a'

// Mark: 40x40. Eight dappled dots of slightly different sizes around one hollow ring.
// The ring is "your note", sitting among standard notes that look like everyone else's.
const DOTS = [
  [8, 8, 4.6], [20, 7.6, 3.6], [32, 8.2, 4.2],
  [7.8, 20, 3.4], /* centre ring */ [32.2, 20, 4.8],
  [8.2, 32, 4.4], [20, 32.4, 4.8], [32, 32, 3.6],
]
const RING = { cx: 20, cy: 20, r: 3.9, w: 2.2 }

function markSvg({ dot, ring, x = 0, y = 0, scale = 1 }) {
  const g = DOTS.map(([cx, cy, r]) => `<circle cx="${cx}" cy="${cy}" r="${r}" fill="${dot}"/>`).join('')
  return `<g transform="translate(${x} ${y}) scale(${scale})">${g}<circle cx="${RING.cx}" cy="${RING.cy}" r="${RING.r}" fill="none" stroke="${ring}" stroke-width="${RING.w}"/></g>`
}

const buf = fs.readFileSync(fontFile)
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength))

// Wordmark: 26px cap height-ish, tracked +0.06em, baseline so it centres on the 40px mark.
const fontSize = 27
const tracking = fontSize * 0.06
let cursor = 0
const parts = []
for (const ch of 'MOTTLE') {
  const glyph = font.charToGlyph(ch)
  const p = glyph.getPath(cursor, 0, fontSize)
  parts.push(p.toPathData(2))
  cursor += (glyph.advanceWidth / font.unitsPerEm) * fontSize + tracking
}
const wordWidth = cursor - tracking
// measure bounds to centre vertically
const full = font.getPath('MOTTLE', 0, 0, fontSize, { letterSpacing: 0.06 })
const bb = full.getBoundingBox()
const capH = -bb.y1
const wordX = 50
const baseline = 20 + capH / 2
const wordD = parts.join(' ')
const totalW = Math.ceil(wordX + wordWidth + 1)

fs.writeFileSync(
  path.join(root, 'src/components/brand/logoPaths.ts'),
  `// Generated by scripts/build-logo.mjs. Do not edit by hand.
export const LOGO_WIDTH = ${totalW}
export const LOGO_HEIGHT = 40
export const WORD_TRANSFORM = 'translate(${wordX} ${baseline.toFixed(2)})'
export const WORD_D = '${wordD}'
export const MARK_DOTS: ReadonlyArray<readonly [number, number, number]> = ${JSON.stringify(DOTS)}
export const MARK_RING = ${JSON.stringify(RING)}
`,
)

const fullLogo = (dot, ring, word) =>
  `${markSvg({ dot, ring })}<path transform="translate(${wordX} ${baseline.toFixed(2)})" d="${wordD}" fill="${word}"/>`

// Source logo (outlined, dark-on-light primary + inverted variant)
fs.writeFileSync(
  path.join(root, 'public/brand/logo.svg'),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${totalW} 40" width="${totalW * 4}" height="160">${fullLogo(INK, INK, INK)}</svg>\n`,
)
fs.writeFileSync(
  path.join(root, 'public/brand/logo-inverted.svg'),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${totalW} 40" width="${totalW * 4}" height="160">${fullLogo(PAPER, LICHEN, PAPER)}</svg>\n`,
)
// Favicon: the mark on an ink tile
const favicon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 48 48"><rect width="48" height="48" rx="10" fill="${INK}"/>${markSvg({ dot: PAPER, ring: LICHEN, x: 4, y: 4 })}</svg>\n`
fs.writeFileSync(path.join(root, 'public/favicon.svg'), favicon)

// 500x500 PNG exports, logo centred with ~12% padding
function exportPng(file, bg, dot, ring, word) {
  const inner = 500 * 0.76
  const s = inner / totalW
  const h = 40 * s
  const x = (500 - inner) / 2
  const y = (500 - h) / 2
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="500" height="500" viewBox="0 0 500 500">${bg ? `<rect width="500" height="500" fill="${bg}"/>` : ''}<g transform="translate(${x} ${y}) scale(${s})">${fullLogo(dot, ring, word)}</g></svg>`
  const png = new Resvg(svg, { fitTo: { mode: 'width', value: 500 } }).render().asPng()
  fs.writeFileSync(path.join(root, 'public/brand', file), png)
}
exportPng('logo-500.png', INK, PAPER, LICHEN, PAPER)
exportPng('logo-500-transparent.png', null, INK, INK, INK)
console.log('logo built', { totalW, capH: capH.toFixed(2) })
